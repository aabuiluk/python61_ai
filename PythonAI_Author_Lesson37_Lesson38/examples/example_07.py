"""Приклад 7. 38.1 · Роль → контекст → завдання → формат

## Зробіть запит перевірюваним

**Факт 7. Явні контекст, дія та формат зменшують двозначність запиту, але результат усе одно перевіряють.**

Схема: роль → дозволені дані → конкретна дія → формат → критерії приймання.

«Порадь щось цікаве» не визначає каталог, адресата або довжину. Сформулюйте дію: обери одну
книгу з переданих кандидатів і поясни спільні ознаки з b01. Роль «редактор магазину» задає стиль,
а не знання про відсутній каталог. Для початківця попросіть просту українську без рекламних обіцянок.

Контекст має містити потрібні записи. Завдання називає обмеження: один ID лише зі списку;
якщо даних бракує, повідом про це. Формат називає ключі book_id, title, reason і типи значень.
Правило 1–2 речень перевіряється окремо; сам текст промпту не примушує API повернути правильну структуру.

У коді build_prompt лише складає рядок. print показує, що саме ви дали б моделі;
вивід не є відповіддю моделі. Ця межа важлива: ми тестуємо підготовку входу, а не здібності LLM.
Не вставляйте повний каталог за замовчуванням, якщо задача потребує лише кількох кандидатів.

prompt.txt існує; роль, контекст, дія, обмеження й формат сформульовані явно.
"""
from pathlib import Path
