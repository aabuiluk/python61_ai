"""Приклад 4. 37.2 · Токени, контекст та inference

## Модель бачить послідовність, а не нашу впевненість

**Факт 4. Промпт змінює вхід поточного inference-запиту; сам по собі він не перенавчає ваги моделі.**

Схема: навчання → ваги; промпт → токенізація → inference з цими вагами → вихідні токени.

Training змінює параметри на навчальних прикладах. Inference застосовує вже навчені параметри.
Few-shot приклади всередині промпту теж належать до входу: це не fine-tuning.
Токен може бути словом, частиною слова або іншим фрагментом; українське слово не обов'язково один токен.
Реальну кількість рахує tokenizer конкретної моделі. split() нижче рахує лише фрагменти за пробілами.

Контекстне вікно має межу. Вхідні інструкції, історія, приклади й джерела займають доступний простір;
модель та API також визначають межі виходу. У вправі бюджет — умовні одиниці, не реальна квота сервісу.
Віднімання показує планування, а не доводить, що запит уміститься в будь-яку модель.

Параметри генерації впливають на вибір продовження. Навіть мала temperature не дає гарантії істини
або абсолютної повторюваності. У живому досліді фіксуємо модель, версію промпту, дату і доступні параметри.

Дефіцит 280 умовних одиниць, новий залишок 120; split не названо tokenizer.
"""
